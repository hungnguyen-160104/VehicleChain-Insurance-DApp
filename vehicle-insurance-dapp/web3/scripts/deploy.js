// scripts/deploy.js
const { ethers, network } = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log(`\n🚗 Deploying Vehicle Insurance DApp to ${network.name}...`);

  // Get deployer account
  const [deployer] = await ethers.getSigners();
  console.log(`📝 Deploying with account: ${deployer.address}`);

  const balance = await deployer.provider.getBalance(deployer.address);
  console.log(`💰 Account balance: ${ethers.formatEther(balance)} ETH`);

  // ─── Deploy contract ───────────────────────────────────────────────────────
  console.log("\n⏳ Deploying VehicleInsuranceDApp...");
  const VehicleInsuranceDApp = await ethers.getContractFactory("VehicleInsuranceDApp");
  const contract = await VehicleInsuranceDApp.deploy();
  await contract.waitForDeployment();

  const contractAddress = await contract.getAddress();
  const deployTx = contract.deploymentTransaction();

  console.log(`✅ VehicleInsuranceDApp deployed to: ${contractAddress}`);
  console.log(`🔍 Transaction hash: ${deployTx.hash}`);

  // Wait for confirmations on testnet
  if (network.name !== "localhost" && network.name !== "hardhat") {
    console.log("⏳ Waiting for block confirmations...");
    await deployTx.wait(5);
    console.log("✅ Confirmed!");
  }

  // ─── Verify basic state ────────────────────────────────────────────────────
  console.log("\n🔍 Verifying deployment...");
  try {
    const totalPolicies = await contract.getTotalPolicies();
    const totalClaims   = await contract.getTotalClaims();
    const balance       = await contract.getContractBalance();
    const owner         = await contract.owner();

    console.log(`   Owner          : ${owner}`);
    console.log(`   Total Policies : ${totalPolicies}`);
    console.log(`   Total Claims   : ${totalClaims}`);
    console.log(`   Contract ETH   : ${ethers.formatEther(balance)} ETH`);
    console.log("✅ Contract state is valid!");
  } catch (err) {
    console.log("⚠️  Could not verify state:", err.message);
  }

  // ─── Save deployment info ──────────────────────────────────────────────────
  const deploymentInfo = {
    contractName    : "VehicleInsuranceDApp",
    network         : network.name,
    contractAddress : contractAddress,
    deployer        : deployer.address,
    deploymentHash  : deployTx.hash,
    timestamp       : new Date().toISOString(),
  };

  const deploymentsDir = path.join(__dirname, "..", "deployments");
  if (!fs.existsSync(deploymentsDir)) fs.mkdirSync(deploymentsDir);

  const deploymentFile = path.join(deploymentsDir, `${network.name}.json`);
  fs.writeFileSync(deploymentFile, JSON.stringify(deploymentInfo, null, 2));
  console.log(`\n📄 Deployment info saved: deployments/${network.name}.json`);

  // ─── Extract ABI và copy sang frontend ────────────────────────────────────
  try {
    const artifactPath = path.join(
      __dirname, "..", "artifacts", "contracts",
      "VehicleInsuranceDApp.sol", "VehicleInsuranceDApp.json"
    );

    if (fs.existsSync(artifactPath)) {
      const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));

      // Tạo file ABI dành cho frontend (format dễ import)
      const abiContent = `// Auto-generated by deploy.js — ${new Date().toISOString()}
// Network: ${network.name} | Address: ${contractAddress}

const VehicleInsuranceABI = ${JSON.stringify(artifact.abi, null, 2)};

module.exports = { VehicleInsuranceABI };
`;

      // Lưu vào web3/deployments/
      const abiFile = path.join(deploymentsDir, `VehicleInsuranceABI.js`);
      fs.writeFileSync(abiFile, abiContent);
      console.log(`📋 ABI saved: deployments/VehicleInsuranceABI.js`);

      // Copy sang frontend nếu tồn tại thư mục
      const frontendContractsDir = path.join(
        __dirname, "..", "..", "contracts"
      );
      if (fs.existsSync(frontendContractsDir)) {
        const frontendAbiFile = path.join(frontendContractsDir, "VehicleInsuranceABI.js");
        fs.writeFileSync(frontendAbiFile, abiContent);
        console.log(`📋 ABI copied to frontend: contracts/VehicleInsuranceABI.js`);
      }
    }
  } catch (err) {
    console.log("⚠️  Could not extract ABI:", err.message);
  }

  // ─── Hướng dẫn bước tiếp theo ─────────────────────────────────────────────
  console.log("\n" + "═".repeat(55));
  console.log("✨ Deployment completed!");
  console.log("═".repeat(55));
  console.log("\n📋 Bước tiếp theo:");
  console.log(`   1. Copy địa chỉ contract: ${contractAddress}`);
  console.log("   2. Cập nhật config/network.js với địa chỉ mới");
  console.log("   3. Dùng ABI từ deployments/VehicleInsuranceABI.js");
  console.log("   4. Cấp quyền garage (nếu cần): capQuyenGarage()");

  if (network.name === "holesky") {
    console.log(`\n🔍 Verify trên Etherscan:`);
    console.log(`   npx hardhat verify --network holesky ${contractAddress}`);
  }

  return contractAddress;
}

main()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error("❌ Deployment failed:", err);
    process.exit(1);
  });
